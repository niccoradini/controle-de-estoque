CREATE TABLE IF NOT EXISTS avenue_count_source (
  material_code TEXT PRIMARY KEY COLLATE NOCASE,
  product_name TEXT NOT NULL,
  category TEXT NOT NULL,
  expected_quantity INTEGER NOT NULL CHECK(expected_quantity >= 0)
);
CREATE TABLE IF NOT EXISTS avenue_count_source_serials (
  serial_number TEXT PRIMARY KEY COLLATE NOCASE,
  material_code TEXT NOT NULL COLLATE NOCASE REFERENCES avenue_count_source(material_code),
  expected INTEGER NOT NULL CHECK(expected IN (0,1))
);
CREATE TABLE IF NOT EXISTS avenue_stock_counts (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','completed','adjusted')),
  created_by INTEGER NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  finalized_at TEXT,
  adjusted_at TEXT
);
CREATE TABLE IF NOT EXISTS avenue_stock_count_items (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  count_id TEXT NOT NULL REFERENCES avenue_stock_counts(id) ON DELETE CASCADE,
  material_code TEXT NOT NULL COLLATE NOCASE,
  product_name TEXT NOT NULL,
  category TEXT NOT NULL,
  stock_mode TEXT NOT NULL CHECK(stock_mode IN ('quantity','serialized')),
  expected_quantity INTEGER NOT NULL CHECK(expected_quantity >= 0),
  counted_quantity INTEGER CHECK(counted_quantity IS NULL OR counted_quantity >= 0),
  note TEXT NOT NULL DEFAULT '',
  updated_at TEXT,
  UNIQUE(count_id,material_code)
);
CREATE TABLE IF NOT EXISTS avenue_stock_count_serials (
  count_id TEXT NOT NULL REFERENCES avenue_stock_counts(id) ON DELETE CASCADE,
  item_id INTEGER NOT NULL REFERENCES avenue_stock_count_items(id) ON DELETE CASCADE,
  serial_number TEXT NOT NULL COLLATE NOCASE,
  expected INTEGER NOT NULL DEFAULT 0 CHECK(expected IN (0,1)),
  found INTEGER NOT NULL DEFAULT 0 CHECK(found IN (0,1)),
  PRIMARY KEY(count_id,serial_number)
);
CREATE INDEX IF NOT EXISTS idx_avenue_stock_count_items ON avenue_stock_count_items(count_id,material_code);
CREATE INDEX IF NOT EXISTS idx_avenue_stock_count_serials ON avenue_stock_count_serials(count_id,item_id);
